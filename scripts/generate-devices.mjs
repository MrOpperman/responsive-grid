import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const SOURCE =
  "https://raw.githubusercontent.com/mozilla-firefox/firefox/main/services/settings/dumps/main/devtools-devices.json";
const OUTPUT = fileURLToPath(new URL("../panel/devices.js", import.meta.url));
const GROUPS = [
  ["phones", "Phones"],
  ["tablets", "Tablets"],
  ["laptops", "Laptops"],
  ["televisions", "Televisions"],
];

const response = await fetch(SOURCE);
if (!response.ok) {
  throw new Error(`Could not download the device list: ${response.status}`);
}

const { data } = await response.json();

// Prefer featured entries, then skip niche touch variants, then shorter names.
const rank = (device) => [
  device.featured ? 0 : 1,
  /touch/i.test(device.name) ? 1 : 0,
  device.name.length,
];

const better = (a, b) => {
  const left = rank(a);
  const right = rank(b);
  return left[0] - right[0] || left[1] - right[1] || left[2] - right[2];
};

const groups = GROUPS.map(([type, label]) => {
  const byWidth = new Map();

  for (const device of data.filter((item) => item.type === type)) {
    const previous = byWidth.get(device.width);
    if (!previous || better(device, previous) < 0) {
      byWidth.set(device.width, {
        name: device.name,
        width: device.width,
        height: device.height,
        featured: Boolean(device.featured),
      });
    }
  }

  const devices = [...byWidth.values()].sort((a, b) => a.width - b.width);
  return { group: type, label, devices };
});

const output =
  "// Generated by scripts/generate-devices.mjs from Firefox's devtools-devices dump.\n" +
  "// One entry per viewport width per device class. Run `npm run devices` to refresh.\n" +
  `const DEVICE_PRESETS = ${JSON.stringify(groups, null, 2)};\n`;

await writeFile(OUTPUT, output);
console.log(`Wrote ${OUTPUT}`);
